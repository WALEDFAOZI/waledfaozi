def t(lang: str, key: str, **kw) -> str:
    s = T.get(lang, T["ar"]).get(key)
    if s is None:
        s = T["ar"][key]
    return s.format(**kw) if kw else s


def cat_label(lang: str, cat: str) -> str:
    table = CATEGORY_LABELS_EN if lang == "en" else CATEGORY_LABELS
    return table.get(cat, cat)
