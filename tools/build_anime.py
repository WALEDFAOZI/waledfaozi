    out, seen = [], set()
    for (key, ar, en, kind, year, studio, genres, rating, seasons, eps, minutes, ongoing,
         eps_ar, eps_en, note_ar, note_en, syn_ar, syn_en) in R:
        assert key not in seen, key
        seen.add(key)
        assert set(genres) <= GENRES and rating in RATINGS, key
        assert syn_ar and syn_en and studio, key
        if kind == "film":
            assert minutes, key
            bucket = "film"
        else:
            n = eps if eps is not None else 0
            bucket = "long" if (ongoing and eps is None) or n > 100 else "medium" if n > 26 else "short"
            if key in ("drstone", "bluelock"):
                bucket = "medium" if key == "drstone" else "short"
            assert eps or eps_ar, key
